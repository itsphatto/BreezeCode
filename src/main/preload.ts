// Exposes a narrow, typed bridge to the renderer. Every path is project-relative and checked in main.js.
import { contextBridge, ipcRenderer, webUtils } from 'electron';

// Whatever the page passes is forwarded as it is: main checks every value it receives (see the ipcMain handlers).
type Listener = (...args: any[]) => void;
const invoke = (ch: string, ...args: unknown[]) => ipcRenderer.invoke(ch, ...args);
const listen = (ch: string, cb: Listener) => {
  const h = (_e: unknown, ...args: unknown[]) => cb(...args);
  ipcRenderer.on(ch, h);
  return () => ipcRenderer.removeListener(ch, h);
};

