const test = require('node:test');
const assert = require('node:assert/strict');
const { chatMessages, claudePrompt, claudeTitle, codexPrompt, typed, oneOff, cleanPrompt } = require('../src/main/agentlogs.js');

const j = o => JSON.stringify(o);
const ts = '2026-11-18T10:00:00.000Z';

test('agentlogs: a Claude Code log becomes one message per prompt and one reply per turn', () => {
  const lines = [
    j({ type: 'queue-operation', operation: 'enqueue', timestamp: ts }),
    j({ type: 'user', timestamp: ts, message: { role: 'user', content: 'fix the login bug' } }),
    j({ type: 'assistant', timestamp: ts, message: { role: 'assistant', content: [{ type: 'thinking', thinking: 'hm' }] } }),
    j({ type: 'assistant', timestamp: ts, message: { role: 'assistant', content: [{ type: 'text', text: 'Looking now.' }] } }),
    j({ type: 'assistant', timestamp: ts, message: { role: 'assistant', content: [{ type: 'tool_use', name: 'Read' }] } }),
    j({ type: 'user', timestamp: ts, message: { role: 'user', content: [{ type: 'tool_result', content: 'file text' }] } }),
    j({ type: 'user', timestamp: ts, isMeta: true, message: { role: 'user', content: [{ type: 'text', text: '[Image: source: C:\\x.png]' }] } }),
    j({ type: 'assistant', timestamp: ts, message: { role: 'assistant', content: [{ type: 'text', text: 'Fixed it.' }] } }),
    j({ type: 'assistant', timestamp: ts, isSidechain: true, message: { role: 'assistant', content: [{ type: 'text', text: 'sub-agent talk' }] } }),
    'not json',
    j({ type: 'user', timestamp: ts, message: { role: 'user', content: [{ type: 'text', text: 'thanks<system-reminder>hidden</system-reminder>' }] } }),
  ];
  const msgs = chatMessages(lines, 'claude');
  assert.deepEqual(msgs.map(m => [m.role, m.text]), [
    ['user', 'fix the login bug'],
    ['agent', 'Looking now.\n\nFixed it.'],
    ['user', 'thanks'],
  ]);
  assert.equal(msgs[0].at, Date.parse(ts));
});

test('agentlogs: Claude Code prompts leave out command echoes, summaries and caveats', () => {
  const u = content => ({ type: 'user', message: { role: 'user', content } });
  assert.equal(claudePrompt(u('<command-name>/compact</command-name>')), null);
  assert.equal(claudePrompt(u('Caveat: The messages below were generated by the user')), null);
  assert.equal(claudePrompt({ ...u('This session is being continued'), isCompactSummary: true }), null);
  assert.equal(claudePrompt(u('hello')), 'hello');
});

test('agentlogs: a Claude Code chat is named by its rename, else nothing', () => {
  assert.equal(claudeTitle({ type: 'custom-title', customTitle: '  Light   mode ' }), 'Light mode');
  assert.equal(claudeTitle({ type: 'agent-name', agentName: 'Board work' }), 'Board work');
  assert.equal(claudeTitle({ type: 'user' }), null);
  assert.equal(claudeTitle(null), null);
});

test('agentlogs: a Codex log skips its set-up messages', () => {
  const item = (role, type, text) => j({ type: 'response_item', timestamp: ts, payload: { type: 'message', role, content: [{ type, text }] } });
  const lines = [
    j({ type: 'session_meta', payload: { id: 's1', cwd: 'C:\\p' } }),
    item('developer', 'input_text', 'You are Codex'),
    item('user', 'input_text', '<environment_context>\n<cwd>C:\\p</cwd></environment_context>'),
    item('user', 'input_text', '# AGENTS.md instructions for C:\\p'),
    item('user', 'input_text', 'add a dark theme'),
    j({ type: 'event_msg', timestamp: ts, payload: { type: 'user_message', message: 'add a dark theme' } }),
    item('assistant', 'output_text', 'Done.'),
  ];
  assert.deepEqual(chatMessages(lines, 'codex').map(m => [m.role, m.text]), [['user', 'add a dark theme'], ['agent', 'Done.']]);
  assert.equal(codexPrompt(JSON.parse(item('user', 'input_text', 'hi'))), 'hi');
});

test('agentlogs: older Codex logs with only events still read', () => {
  const ev = (type, message) => j({ type: 'event_msg', timestamp: ts, payload: { type, message } });
  const msgs = chatMessages([ev('user_message', 'hi there'), ev('agent_message', 'Hello.'), ev('agent_message', 'Anything else?')], 'codex');
  assert.deepEqual(msgs.map(m => [m.role, m.text]), [['user', 'hi there'], ['agent', 'Hello.\n\nAnything else?']]);
});

test('agentlogs: Breeze\'s own one-off questions are not listed as chats', () => {
  assert.ok(oneOff('You are an expert developer generating a concise Git commit message.'));
  assert.ok(oneOff('Write a short title (2 to 5 words) for a chat that starts with the request below.'));
  assert.ok(oneOff('Explain this TypeScript code from src/a.ts (line 3) to a developer'));
  assert.ok(oneOff('Rewrite the prompt below so a coding agent can act on it well.'));
  assert.ok(oneOff(require('../src/main/secondbrain.js').summarizePrompt('')));
  assert.ok(!oneOff('fix the login bug'));
  assert.ok(!typed('<environment_context>'));
  assert.ok(typed('use <div> here'));
  assert.equal(cleanPrompt('look\n[Image: source: C:\\a.png]'), 'look');
});
